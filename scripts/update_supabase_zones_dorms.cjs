async function update() {
  try {
    const { data } = await supabase.from('system_settings').select('settings').eq('id', 'current').single();
    const currentSettings = data?.settings || {};
    const newSettings = {
      ...currentSettings,
      storeAddress: 'Bostanbükü, Safranbolu / Karabük',
      storeLatitude: 41.212095,
      storeLongitude: 32.6732255,
      deliveryZones: DEFAULT_ZONES,
      dormitories: DEFAULT_DORMS,
    };

    const { error } = await supabase
      .from('system_settings')
      .upsert({ id: 'current', settings: newSettings, updated_at: new Date().toISOString() });

    if (error) {
      console.error('Supabase error:', error.message);
    } else {
      console.log('Successfully updated Supabase settings with 23 dorms and 5 distance zones!');
    }
  } catch (err) {
    console.warn('Network / Cloudflare exception during Supabase update:', err.message);
  }
}

update();
