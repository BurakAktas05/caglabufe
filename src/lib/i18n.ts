export const DEFAULT_LOCALE: Locale = 'tr';

export function getTranslation(
  locale: Locale,
  key: string,
  fallbackOrParams?: string | Record<string, string | number>,
  params?: Record<string, string | number>
): string {
  const dict = TRANSLATIONS[locale] || TRANSLATIONS[DEFAULT_LOCALE];
  const defaultDict = TRANSLATIONS[DEFAULT_LOCALE];
  const fallbackStr = typeof fallbackOrParams === 'string' ? fallbackOrParams : undefined;
  const actualParams = typeof fallbackOrParams === 'object' ? fallbackOrParams : params;

  let text = dict[key] || defaultDict[key] || fallbackStr || key;

  if (actualParams) {
    Object.entries(actualParams).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }

  return text;
}
